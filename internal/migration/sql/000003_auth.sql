CREATE TABLE scan_api_keys (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 tenant VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
 subject VARCHAR(128) NOT NULL,
 token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 scopes_json JSON NOT NULL,
 expires_at DATETIME(3) NOT NULL,
 revoked_at DATETIME(3) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE scan_audit_events (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 tenant VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
 key_id BIGINT UNSIGNED NULL,
 subject VARCHAR(128) NOT NULL,
 action VARCHAR(128) NOT NULL,
 resource VARCHAR(255) NOT NULL,
 outcome VARCHAR(32) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 KEY idx_audit_tenant_time(tenant,created_at,id)
) ENGINE=InnoDB;
